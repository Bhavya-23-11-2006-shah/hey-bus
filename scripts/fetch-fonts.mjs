// Downloads the app's fonts (Caveat, Permanent Marker, Nunito) once and keeps them
// inside the project, so the website and the APK both render the real handwriting
// with no network needed. Re-run any time to refresh.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.resolve(here, '..', 'sticky-days', 'fonts');

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0 Safari/537.36';
const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Caveat:wght@500;700&family=Nunito:wght@500;700;800&family=Permanent+Marker&display=swap';

const WANTED_FAMILIES = new Set(['caveat', 'nunito', 'permanent marker']);
const WANTED_SUBSETS = new Set(['latin', 'latin-ext']);

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text();

// Google returns "/* subset */ @font-face { ... }" blocks.
const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
fs.mkdirSync(outDir, { recursive: true });

const rules = [];
for (const [, subset, body] of blocks) {
  if (!WANTED_SUBSETS.has(subset)) continue;
  const family = (body.match(/font-family:\s*'([^']+)'/) || [])[1];
  const weight = (body.match(/font-weight:\s*(\d+)/) || [])[1];
  const src = (body.match(/url\((https:[^)]+\.woff2)\)/) || [])[1];
  const range = (body.match(/unicode-range:\s*([^;]+);/) || [])[1];
  if (!family || !weight || !src) continue;
  if (!WANTED_FAMILIES.has(family.toLowerCase())) continue;

  const slug = family.toLowerCase().replace(/\s+/g, '-');
  const file = `${slug}-${weight}-${subset}.woff2`;
  const target = path.join(outDir, file);
  if (!fs.existsSync(target)) {
    const buf = Buffer.from(await (await fetch(src, { headers: { 'User-Agent': UA } })).arrayBuffer());
    fs.writeFileSync(target, buf);
  }
  rules.push(
    `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:swap;` +
      `src:url('${file}') format('woff2')${range ? `;unicode-range:${range.trim()}` : ''}}`
  );
}

if (!rules.length) throw new Error('no font files found in the Google CSS response');

const header =
  '/* Sticky Days fonts, kept inside the app (SIL Open Font License). Generated by scripts/fetch-fonts.mjs */\n';
fs.writeFileSync(path.join(outDir, 'fonts.css'), header + rules.join('\n') + '\n');

const sizes = fs
  .readdirSync(outDir)
  .filter((f) => f.endsWith('.woff2'))
  .map((f) => `${f} ${(fs.statSync(path.join(outDir, f)).size / 1024).toFixed(1)}KB`);
console.log(`fonts written to ${outDir}\n` + sizes.join('\n'));
